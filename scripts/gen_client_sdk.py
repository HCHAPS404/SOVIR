"""Generate the typed TS client in packages/client-sdk from the OpenAPI
contract. Deterministic, offline, no network. Usage:

    uv run scripts/gen_client_sdk.py          # writes src/
    uv run scripts/gen_client_sdk.py --check  # fail if src/ is stale

The emitted client is thin by design: one method per contract operation,
types derived from component schemas. Anything the contract doesn't
describe is `unknown` — never guessed.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "packages" / "contracts" / "openapi" / "backend-dev.v0.yaml"
EVENT_SCHEMA = ROOT / "packages" / "contracts" / "schemas" / "observed-event.schema.json"
OUT = ROOT / "packages" / "client-sdk" / "src"
HEADER = "// Generated by scripts/gen_client_sdk.py from backend-dev.v0.yaml.\n// Do not edit by hand — regenerate instead.\n\n"

import yaml


def ts_type(schema: dict) -> str:
    """Map a (small) JSON-schema node to a TS type. Unknown → unknown."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1].split(".")[0]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        item = ts_type(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if t == "object" and schema.get("properties"):
        return "Record<string, unknown>"
    if t == "object":
        return "Record<string, unknown>"
    if isinstance(t, list) and "null" in t:
        base = [x for x in t if x != "null"]
        inner = ts_type({**schema, "type": base[0]}) if base else "unknown"
        return f"{inner} | null"
    return "unknown"


def iface(name: str, schema: dict) -> str:
    """Render one component schema as a TS interface."""
    req = set(schema.get("required", []))
    props = schema.get("properties", {})
    lines = [f"export interface {name} {{"]
    for pname, pschema in props.items():
        optional = "" if pname in req else "?"
        if pschema.get("readOnly"):
            lines.append(f"  readonly {pname}{optional}: {ts_type(pschema)};")
        else:
            lines.append(f"  {pname}{optional}: {ts_type(pschema)};")
    if not props:
        lines.append("  [k: string]: unknown;")
    lines.append("}")
    return "\n".join(lines)


def method_name(method: str, path: str) -> str:
    """/v1/devices/{id}/revoke POST -> revokeDevice; /v1/me/audit GET -> getMeAudit"""
    segs = [s for s in path.split("/") if s and s != "v1"]
    verb = {"get": "get", "post": "post", "delete": "delete", "put": "put"}[method]
    words = [verb]
    for s in segs:
        if s.startswith("{"):
            words.append("byId")
            continue
        for part in re.split(r"[-_]", s):
            if part:
                words.append(part)
    # Special-case stable names that read better than the mechanical ones.
    name = words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])
    overrides = {
        "postAuthDevSession": "devSession",
        "postAuthLogout": "logout",
        "getAuthWhoami": "whoami",
        "postDevices": "registerDevice",
        "postDevicesByIdRevoke": "revokeDevice",
        "postConsents": "grantConsent",
        "postConsentsByIdRevoke": "revokeConsent",
        "postEvents": "ingestEvent",
        "getEvents": "listEvents",
        "getDevices": "listDevices",
        "getInterventions": "listInterventions",
        "postInterventionsDispatch": "dispatchInterventions",
        "getMeData": "exportData",
        "deleteMeData": "purgeData",
        "getMeAudit": "listAudit",
        "postMeRetention": "enforceRetention",
        "postInferenceAssess": "assessInference",
        "postIntelPull": "pullIntel",
        "getIntel": "listIntel",
        "postWebhooks": "registerWebhook",
        "getWebhooks": "listWebhooks",
        "postWebhooksByIdRevoke": "revokeWebhook",
        "getVersion": "version",
        "getMetrics": "metrics",
    }
    return overrides.get(name, name)


def body_schema(op: dict) -> str | None:
    try:
        s = op["requestBody"]["content"]["application/json"]["schema"]
        return ts_type(s)
    except KeyError:
        return None


def response_schema(op: dict) -> str:
    """TS return type: schema ref, 'string' for text/plain, 'void' for
    no-content 2xx, 'unknown' when the contract doesn't declare one."""
    for code in ("200", "201", "202"):
        r = op.get("responses", {}).get(code)
        if r is None:
            continue
        content = r.get("content", {})
        if "application/json" in content:
            return ts_type(content["application/json"].get("schema", {}))
        if "text/plain" in content:
            return "string"
        return "unknown"
    if "204" in op.get("responses", {}):
        return "void"
    return "unknown"


def main() -> int:
    doc = yaml.safe_load(CONTRACT.read_text(encoding="utf-8"))
    schemas = dict(doc.get("components", {}).get("schemas", {}))
    # Resolve the one external schema ref (ObservedEvent).
    schemas["ObservedEvent"] = json.loads(EVENT_SCHEMA.read_text(encoding="utf-8"))

    types_ts = HEADER + "\n\n".join(
        iface(name, s) for name, s in schemas.items() if isinstance(s, dict)
    ) + "\n"

    methods: list[str] = []
    seen: set[str] = set()
    for path, item in doc.get("paths", {}).items():
        for method in ("get", "post", "put", "delete"):
            if method not in item:
                continue
            op = item[method]
            name = method_name(method, path)
            if name in seen:
                name = f"{name}{method.title()}"
            seen.add(name)
            body = body_schema(op)
            ret = response_schema(op)
            def tref(t: str) -> str:
                if t.endswith("[]") and t[:-2] in schemas:
                    return f"T.{t[:-2]}[]"
                return f"T.{t}" if t in schemas else t
            if body:
                body = tref(body)
            ret = tref(ret)
            summary = op.get("summary", "").strip()
            docline = f"  /** {summary} */\n" if summary else ""
            # Path params → function args.
            params = re.findall(r"\{(\w+)\}", path)
            args = [f"{p}: string" for p in params]
            if body:
                args.append(f"body: {body}")
            has_limit = any(
                p.get("name") == "limit" for p in op.get("parameters", [])
            )
            if has_limit:
                args.append("limit?: number")
            args.append("options?: RequestOptions")
            tp = path
            for p in params:
                tp = tp.replace("{" + p + "}", "${encodeURIComponent(" + p + ")}")
            qs = ' + (limit ? `?limit=${limit}` : "")' if has_limit else ""
            url = f"`{tp}`{qs}"
            if path == "/v1/events" and method == "post":
                # Idempotency-Key is mandatory on ingest (contract-checked).
                args = [a for a in args if not a.startswith("options?:")]
                args.append("idempotencyKey: string")
                args.append("options?: RequestOptions")
                opts = (
                    "{ ...options, headers: { ...(options?.headers ?? {}), "
                    "'idempotency-key': idempotencyKey } }"
                )
            else:
                opts = "options"
            body_arg = ", body" if body else ", undefined"
            if ret == "void":
                methods.append(
                    f"{docline}  async {name}({', '.join(args)}): Promise<void> {{\n"
                    f'    await this.request("{method.upper()}", {url}'
                    f"{body_arg}, {opts});\n  }}"
                )
                continue
            reader = "text()" if ret == "string" else "json()"
            call = (
                f'(await this.request("{method.upper()}", {url}{body_arg}, '
                f"{opts})).{reader}"
            )
            methods.append(
                f"{docline}  async {name}({', '.join(args)}): Promise<{ret}> {{\n"
                f"    return (await {call}) as {ret};\n  }}"
            )

    client = HEADER + '''import type * as T from "./types.js";

export interface RequestOptions {
  headers?: Record<string, string>;
  signal?: AbortSignal;
}

export class SovirApiError extends Error {
  constructor(
    public status: number,
    public code: string,
    public requestId: string,
    public retryable: boolean,
  ) {
    super(`SOVIR API ${status}: ${code} (${requestId})`);
  }
}

/** Typed client for backend-dev.v0. Token stays caller-managed — the
 *  console BFF keeps it in an httpOnly cookie; native clients hold it in
 *  memory. Never logged, never persisted by this client. */
export class SovirClient {
  constructor(
    private baseUrl: string,
    private token?: string,
  ) {}

  private async request(
    method: string,
    path: string,
    body?: unknown,
    options?: RequestOptions,
  ): Promise<Response> {
    const res = await fetch(`${this.baseUrl}${path}`, {
      method,
      headers: {
        ...(body !== undefined ? { "content-type": "application/json" } : {}),
        ...(this.token ? { authorization: `Bearer ${this.token}` } : {}),
        ...(options?.headers ?? {}),
      },
      body: body !== undefined ? JSON.stringify(body) : undefined,
      signal: options?.signal,
    });
    if (!res.ok) {
      let code = "unknown";
      let requestId = "";
      let retryable = false;
      try {
        const env = (await res.json()) as {
          error?: { code?: string; request_id?: string; retryable?: boolean };
        };
        code = env.error?.code ?? code;
        requestId = env.error?.request_id ?? requestId;
        retryable = env.error?.retryable ?? retryable;
      } catch {
        /* non-JSON error body */
      }
      throw new SovirApiError(res.status, code, requestId, retryable);
    }
    return res;
  }

'''
    client += "\n\n".join(methods)
    client += "\n}\n\nexport type { T };\n"

    files = {"types.ts": types_ts, "index.ts": client}
    if "--check" in sys.argv:
        stale = [
            f for f, want in files.items()
            if not (OUT / f).exists() or (OUT / f).read_text() != want
        ]
        if stale:
            print(f"STALE: {stale} — run uv run scripts/gen_client_sdk.py")
            return 1
        print("client-sdk generated output is up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for f, content in files.items():
        (OUT / f).write_text(content, encoding="utf-8")
    print(f"generated {len(files)} files in {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
