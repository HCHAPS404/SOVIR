// Generates ../brand-domains.js from ml/brand-domains.json — the single
// source of truth shared with the visual voter (ml/pipelines/train_visual.py).
// Run from apps/extension:  node scripts/build-brand-domains.js
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(
  readFileSync(join(here, "..", "..", "..", "ml", "brand-domains.json"), "utf8"),
);

const norm = (s) =>
  String(s)
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

const brands = [];
for (const [name, domains] of Object.entries(src)) {
  if (name.startsWith("_") || !Array.isArray(domains)) continue;
  const n = norm(name);
  if (n.length < 4) continue; // too short to claim safely in page text
  brands.push({
    n,
    m: n.includes(" "), // multi-word names are distinctive on their own
    d: domains.map((d) => String(d).toLowerCase()),
  });
}
brands.sort((a, b) => a.n.localeCompare(b.n));

const out = `// GENERATED by scripts/build-brand-domains.js from ml/brand-domains.json.
// Curated brand -> legit domains (same list the visual ONNX voter trains
// on). A page presenting one of these brand identities from any other host
// fires DOM_BRAND_MISMATCH. Do not edit by hand.
(function attach(global) {
  "use strict";
  global.SOVIR_BRAND_DOMAINS = ${JSON.stringify(brands)};
})(globalThis);
`;
writeFileSync(join(here, "..", "brand-domains.js"), out);
console.log(`brand-domains.js: ${brands.length} brands`);
